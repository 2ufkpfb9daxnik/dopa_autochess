# -*- coding: utf-8 -*-
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1] / "src" / "data" / "relics"
DETAIL_RE = re.compile(r"(## 詳細な説明文\n\n)(.+?)(\n\n## )", re.S)
BRIEF_RE = re.compile(r"(## 簡単な説明文\n\n)(.+?)(\n\n## )", re.S)


def polish_detail(d: str) -> str:
    d = re.sub(
        r"最大体力が高くなる。いまの体力も、同じ量だけ高くなる。新しい最大体力は超えない。高くなる量は(\d+)である。",
        r"最大体力が\1高くなる。いまの体力も、同じ量だけ高くなる。新しい最大体力は超えない。",
        d,
    )
    d = re.sub(
        r"属性耐性が高くなる。どの属性の攻撃にも入る。高くなる量は(\d+)%である。",
        r"属性耐性が\1%高くなる。どの属性の攻撃にも入る。",
        d,
    )
    d = re.sub(
        r"その攻撃の与ダメージは高くなる。高くなる割合は(\d+)%である。",
        r"その攻撃の与ダメージは\1%高くなる。",
        d,
    )
    d = re.sub(
        r"味方全員の与ダメージが高くなる。装備者自身も入る。高くなる割合は(\d+)%である。",
        r"味方全員の与ダメージが\1%高くなる。装備者自身も入る。",
        d,
    )
    d = re.sub(
        r"味方全員の速度が高くなる。装備者自身も入る。高くなる量は(\d+)である。",
        r"味方全員の速度が\1高くなる。装備者自身も入る。",
        d,
    )
    d = re.sub(
        r"前衛の味方の防御力が高くなる。装備者が前衛なら、装備者も入る。後衛は入らない。高くなる量は(\d+)である。",
        r"前衛の味方の防御力が\1高くなる。装備者が前衛なら、装備者も入る。後衛は入らない。",
        d,
    )
    d = re.sub(
        r"後衛の味方の与ダメージが高くなる。装備者が後衛なら、装備者も入る。前衛は入らない。高くなる割合は(\d+)%である。",
        r"後衛の味方の与ダメージが\1%高くなる。装備者が後衛なら、装備者も入る。前衛は入らない。",
        d,
    )
    d = re.sub(
        r"その隣の味方の与ダメージが高くなる。隣は、同じ段のすぐ左とすぐ右である。前衛なら前衛、後衛なら後衛である。端で隣がいない側は入らない。装備者自身は入らない。高くなる割合は(\d+)%である。",
        r"その隣の味方の与ダメージが\1%高くなる。隣は、同じ段のすぐ左とすぐ右である。前衛なら前衛、後衛なら後衛である。端で隣がいない側は入らない。装備者自身は入らない。",
        d,
    )
    d = re.sub(
        r"味方全員のクリティカル率が高くなる。装備者自身も入る。高くなる量は(\d+)である。",
        r"味方全員のクリティカル率が\1高くなる。装備者自身も入る。",
        d,
    )
    d = re.sub(
        r"味方全員の属性耐性が高くなる。装備者自身も入る。どの属性の攻撃にも入る。高くなる量は(\d+)%である。",
        r"味方全員の属性耐性が\1%高くなる。装備者自身も入る。どの属性の攻撃にも入る。",
        d,
    )
    d = re.sub(
        r"残っている味方全員の与ダメージが、その戦闘のあいだ高くなる。装備者自身も、残っていれば入る。倒れた味方は入らない。高くなる割合は(\d+)%である。",
        r"残っている味方全員の与ダメージが、その戦闘のあいだ\1%高くなる。装備者自身も、残っていれば入る。倒れた味方は入らない。",
        d,
    )
    d = re.sub(
        r"味方全員の貫通率が高くなる。装備者自身も入る。高くなる割合は(\d+)%である。",
        r"味方全員の貫通率が\1%高くなる。装備者自身も入る。",
        d,
    )
    d = re.sub(
        r"装備者と、その隣の味方のターゲット優先度が高くなる。隣は、同じ段のすぐ左とすぐ右である。前衛なら前衛、後衛なら後衛である。端で隣がいない側は入らない。高くなる量は(\d+)である。",
        r"装備者と、その隣の味方のターゲット優先度が\1高くなる。隣は、同じ段のすぐ左とすぐ右である。前衛なら前衛、後衛なら後衛である。端で隣がいない側は入らない。",
        d,
    )
    d = re.sub(
        r"合計10回のうち、(\d+)回で獲得する。\1である。獲得する数は(\d+)である。",
        r"合計10回のうち\1回当たり、無料更新が\2回入手できる。",
        d,
    )
    d = re.sub(
        r"その時点の連敗が、(\d+)以上なら、無料更新を獲得する。連敗は\1である。獲得する数は(\d+)である。",
        r"その時点の連敗が\1以上なら、無料更新が\2回入手できる。",
        d,
    )
    d = re.sub(r"効果値の戻りゴールドの欄は、星1あたりの戻りである。1である。", r"星1あたりの戻りは1ゴールドである。", d)
    d = re.sub(r"効果値の多い段の欄は(\d+)、少ない段の欄は(\d+)である。", r"多い段は\1、少ない段は\2である。", d)
    d = re.sub(r"高くなる割合は(\d+)%である。", r"\1%高くなる。", d)
    d = re.sub(r"高くなる量は(\d+)%である。", r"\1%高くなる。", d)
    d = re.sub(r"高くなる量は(\d+)である。", r"\1高くなる。", d)
    d = re.sub(r"低くなる割合は(\d+)%である。", r"\1%低くなる。", d)
    d = re.sub(r"低くなる量は(\d+)である。", r"\1低くなる。", d)
    d = re.sub(r"獲得する数は(\d+)である。", r"\1回入手できる。", d)
    d = re.sub(r"1戦闘で(\d+)回までである。", r"1戦闘で\1回まで戻る。", d)
    d = re.sub(
        r"速度が高くなる。1回で(\d+)高くなる。上限は(\d+)である。",
        r"速度が、1回あたり\1、上限\2まで高くなる。",
        d,
    )
    d = re.sub(
        r"最大体力が高くなり、与ダメージも高くなる。どちらも(\d+)%である。",
        r"最大体力と与ダメージがどちらも\1%高くなる。",
        d,
    )
    d = re.sub(
        r"与ダメージも高くなる。最大体力と与ダメージがどちらも(\d+)%高くなる。",
        r"最大体力と与ダメージがどちらも\1%高くなる。",
        d,
    )
    d = re.sub(r"。{2,}", "。", d)
    return d.strip()


def main() -> None:
    changed = 0
    for path in sorted(ROOT.glob("*.md")):
        text = path.read_text(encoding="utf-8")
        original = text
        dm = DETAIL_RE.search(text)
        if dm:
            text = text[: dm.start(2)] + polish_detail(dm.group(2)) + text[dm.end(2) :]
        bm = BRIEF_RE.search(text)
        if bm:
            brief = bm.group(2).strip()
            if path.name == "009.md":
                brief = "通常の攻撃が当たると、最大体力の8%だけ体力が戻る。1戦闘で3回まで。"
            elif path.name == "018.md":
                brief = "攻撃するたび、速度が4高くなる。上限は12。"
            elif path.name == "041.md":
                brief = "入手したとき、無料更新が5回入手できる。入手したら消える。"
            elif path.name == "063.md":
                brief = "ラウンド開始時、所持ゴールドが多いほど無料更新が入手できる。40以上で2回、20以上で1回。"
            if brief != bm.group(2).strip():
                text = text[: bm.start(2)] + brief + text[bm.end(2) :]
        if text != original:
            path.write_text(text, encoding="utf-8", newline="\n")
            changed += 1

    residual = []
    awkward = []
    for path in sorted(ROOT.glob("*.md")):
        text = path.read_text(encoding="utf-8")
        dm = DETAIL_RE.search(text)
        if not dm:
            continue
        detail = dm.group(2)
        if "効果値の" in detail or "この欄は%" in detail:
            residual.append(path.name)
        if re.search(r"高くなる割合は|高くなる量は|獲得する数は|低くなる割合は|低くなる量は|効果値の", detail):
            awkward.append(path.name)
    print(f"changed={changed} residual={residual} awkward={len(awkward)}")
    for name in awkward[:20]:
        print(" ", name)


if __name__ == "__main__":
    main()
